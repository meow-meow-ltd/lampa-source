#!/usr/bin/env python3
"""Prepare the staging copy of the production DB for the Node staging stand.

Does exactly three data-level things on the *copy* (never on the production
file, the script refuses a DB under /opt/lampa/data):

  1. replaces settings.admin_password and settings.admin_token with throwaway
     staging values; production values are never read and never printed;
  2. creates/refreshes one test device (device_access.status='allowed',
     token_hash=sha256(test device token)) so the smoke can exercise the
     device-token guard;
  3. writes the staging-only values to --env-out (mode 0600, outside git) and
     re-asserts integrity_check=ok, schema_version=7, journal_mode=delete.

No DDL: only rows in existing tables are touched. Values already present in an
existing --env-out are reused, so repeated runs are idempotent and do not force
a container restart; pass --rotate to generate fresh ones deliberately.

Attribution: ported from poc/s11-delivery/scripts/prepare_db.py (S11 §2.1),
extended with the device-token fixture and the schema/journal assertions.
"""
import argparse
import base64
import hashlib
import json
import os
import secrets
import sqlite3
import stat
import sys

PROD_DIR = "/opt/lampa/data"
APP_TABLES = [
    "bookmark_events",
    "bookmarks",
    "device_access",
    "ip_rate_limits",
    "profile_settings",
    "profiles",
    "schema_version",
    "settings",
    "timeline",
    "timeline_events",
]
EXPECTED_TABLES = sorted(APP_TABLES + ["sqlite_sequence"])

ENV_KEYS = {
    "totp": "TOTP_SECRET",
    "password": "LAMPA_STAGING_ADMIN_PASSWORD",
    "admin_token": "LAMPA_STAGING_ADMIN_TOKEN",
    "device_token": "LAMPA_STAGING_DEVICE_TOKEN",
    "device_id": "LAMPA_STAGING_DEVICE_ID",
}

ENV_HEADER = """# Lampa staging stand - STAGING-ONLY test values. Never production secrets.
# Generated by deploy/scripts/prepare_staging_db.py; mode 0600; outside git.
# Consumed twice: as compose env_file (HOST/PORT/DB_PATH/TOTP_SECRET) and by
# deploy/scripts/smoke.sh (LAMPA_STAGING_* test credentials).
"""


def die(msg, code=2):
    print("prepare_staging_db: ERROR: " + msg, file=sys.stderr)
    raise SystemExit(code)


def inside_prod(path):
    real = os.path.realpath(path)
    prod = os.path.realpath(PROD_DIR)
    return real == prod or real.startswith(prod + os.sep)


def valid_b32(text):
    try:
        padded = text.upper() + "=" * ((8 - len(text) % 8) % 8)
        base64.b32decode(padded)
    except Exception:
        return False
    return len(text) >= 16


def new_b32_secret():
    return base64.b32encode(os.urandom(20)).decode().rstrip("=")


def new_password():
    return "stg-" + secrets.token_hex(12)


def new_hex_token():
    return secrets.token_hex(32)


def read_env_file(path):
    values = {}
    if not os.path.exists(path):
        return values
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            values[key.strip()] = value.strip()
    return values


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def resolve_secrets(args, prev):
    rotate = args.rotate
    totp = args.totp_secret or (None if rotate else prev.get(ENV_KEYS["totp"]))
    password = args.admin_password or (None if rotate else prev.get(ENV_KEYS["password"]))
    admin_token = None if rotate else prev.get(ENV_KEYS["admin_token"])
    device_token = None if rotate else prev.get(ENV_KEYS["device_token"])
    device_id = args.device_id or prev.get(ENV_KEYS["device_id"]) or "staging-smoke-device"

    if not totp or not valid_b32(totp):
        totp = new_b32_secret()
    if not password or len(password) < 12:
        password = new_password()
    if not admin_token or len(admin_token) < 32:
        admin_token = new_hex_token()
    if not device_token or len(device_token) < 32:
        device_token = new_hex_token()
    return {
        "totp": totp,
        "password": password,
        "admin_token": admin_token,
        "device_token": device_token,
        "device_id": device_id,
    }


def verify(dest_path, secrets_):
    con = sqlite3.connect("file:" + dest_path + "?mode=ro", uri=True, timeout=15)
    con.execute("PRAGMA busy_timeout=15000")
    try:
        integrity = con.execute("PRAGMA integrity_check").fetchone()[0]
        quick = con.execute("PRAGMA quick_check").fetchone()[0]
        journal = con.execute("PRAGMA journal_mode").fetchone()[0]
        version_row = con.execute("SELECT version FROM schema_version WHERE id=1").fetchone()
        version = version_row[0] if version_row else None
        tables = [r[0] for r in con.execute(
            "SELECT name FROM sqlite_schema WHERE type='table' ORDER BY name").fetchall()]
        counts = {t: con.execute('SELECT COUNT(*) FROM "' + t + '"').fetchone()[0]
                  for t in tables}
        admin_keys = [r[0] for r in con.execute(
            "SELECT key FROM settings WHERE key IN ('admin_password','admin_token') "
            "AND value IS NOT NULL AND value <> '' ORDER BY key").fetchall()]
        token_hash = hashlib.sha256(secrets_["device_token"].encode()).hexdigest()
        devices = con.execute(
            "SELECT status, token_hash FROM device_access WHERE device_id=?",
            (secrets_["device_id"],)).fetchall()
        device_statuses = sorted({d[0] for d in devices})
        device_token_match = len(devices) == 1 and devices[0][1] == token_hash
        duplicates = con.execute(
            "SELECT COUNT(*) FROM device_access WHERE device_id=?",
            (secrets_["device_id"],)).fetchone()[0]
    finally:
        con.close()

    errors = []
    if integrity != "ok":
        errors.append("integrity_check=" + str(integrity))
    if quick != "ok":
        errors.append("quick_check=" + str(quick))
    if version != 7:
        errors.append("schema_version=" + str(version) + " (expected 7)")
    if journal != "delete":
        errors.append("journal_mode=" + str(journal) + " (expected delete)")
    if sorted(tables) != EXPECTED_TABLES:
        errors.append("tables mismatch: " + ",".join(sorted(tables)))
    if len(admin_keys) != 2:
        errors.append("admin settings keys not replaced: " + ",".join(admin_keys))
    if not device_token_match or device_statuses != ["allowed"]:
        errors.append("test device not effective (status=" + ",".join(device_statuses) + ")")
    return {
        "ok": not errors,
        "errors": errors,
        "integrity_check": integrity,
        "quick_check": quick,
        "schema_version": version,
        "journal_mode": journal,
        "tables": sorted(tables),
        "table_count": len(tables),
        "row_counts": counts,
        "admin_keys_replaced": len(admin_keys) == 2,
        "device_id": secrets_["device_id"],
        "device_rows": duplicates,
        "device_status": (device_statuses[0] if len(device_statuses) == 1 else device_statuses),
        "device_token_match": device_token_match,
    }


def write_env(path, secrets_):
    lines = [ENV_HEADER]
    lines.append("HOST=0.0.0.0")
    lines.append("PORT=3000")
    lines.append("DB_PATH=/data/database.sqlite")
    lines.append(ENV_KEYS["totp"] + "=" + secrets_["totp"])
    lines.append(ENV_KEYS["password"] + "=" + secrets_["password"])
    lines.append(ENV_KEYS["admin_token"] + "=" + secrets_["admin_token"])
    lines.append(ENV_KEYS["device_token"] + "=" + secrets_["device_token"])
    lines.append(ENV_KEYS["device_id"] + "=" + secrets_["device_id"])
    body = "\n".join(lines) + "\n"
    directory = os.path.dirname(os.path.abspath(path)) or "."
    os.makedirs(directory, exist_ok=True)
    tmp = path + ".tmp." + str(os.getpid())
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(body)
            fh.flush()
            os.fsync(fh.fileno())
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)
    os.chmod(path, 0o600)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="/opt/lampa/staging-data/database.sqlite",
                    help="staging DB copy (must not be inside " + PROD_DIR + ")")
    ap.add_argument("--env-out", default="/opt/lampa/staging-data/env.staging",
                    help="staging-only env file to write (mode 0600)")
    ap.add_argument("--device-id", default=None,
                    help="test device_id (default: keep existing or staging-smoke-device)")
    ap.add_argument("--admin-password", default=None,
                    help="override test admin password (never printed)")
    ap.add_argument("--totp-secret", default=None,
                    help="override base32 test TOTP secret (never printed)")
    ap.add_argument("--rotate", action="store_true",
                    help="generate fresh test values even if --env-out already has them")
    args = ap.parse_args()

    if inside_prod(args.db):
        die("refusing to modify a DB inside the production data directory")
    if inside_prod(args.env_out):
        die("refusing to write the env file inside the production data directory")
    if not os.path.isfile(args.db):
        die("staging DB not found: " + args.db + " (run deploy/scripts/db_copy.sh first)", 2)

    prev = read_env_file(args.env_out)
    secrets_ = resolve_secrets(args, prev)

    con = sqlite3.connect(args.db, timeout=15)
    con.execute("PRAGMA busy_timeout=15000")
    now_ms = int(__import__("time").time() * 1000)
    try:
        with con:
            for key, value in (("admin_password", secrets_["password"]),
                               ("admin_token", secrets_["admin_token"])):
                con.execute(
                    "INSERT INTO settings(key, value, visible) VALUES(?, ?, 0) "
                    "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                    (key, value),
                )
            token_hash = hashlib.sha256(secrets_["device_token"].encode()).hexdigest()
            rows = con.execute(
                "SELECT id FROM device_access WHERE device_id=?",
                (secrets_["device_id"],)).fetchall()
            if rows:
                for (row_id,) in rows:
                    con.execute(
                        "UPDATE device_access SET status='allowed', token_hash=?, "
                        "attempts=0, blocked_until=NULL, last_attempt_at=?, last_seen_at=?, "
                        "ip=?, user_agent=? WHERE id=?",
                        (token_hash, now_ms, now_ms, "127.0.0.1",
                         "lampa-staging-prepare", row_id))
            else:
                con.execute(
                    "INSERT INTO device_access(device_id, ip, user_agent, status, attempts, "
                    "last_attempt_at, last_seen_at, token_hash) "
                    "VALUES(?, ?, ?, 'allowed', 0, ?, ?, ?)",
                    (secrets_["device_id"], "127.0.0.1", "lampa-staging-prepare",
                     now_ms, now_ms, token_hash))
    finally:
        con.close()

    write_env(args.env_out, secrets_)
    result = verify(args.db, secrets_)
    env_mode = stat.S_IMODE(os.stat(args.env_out).st_mode)
    result.update({
        "db": os.path.realpath(args.db),
        "db_mode": oct(stat.S_IMODE(os.stat(args.db).st_mode))[2:].zfill(4),
        "db_size": os.path.getsize(args.db),
        "env_out": os.path.realpath(args.env_out),
        "env_mode": oct(env_mode)[2:].zfill(4),
        "env_keys": [ENV_KEYS["totp"], ENV_KEYS["password"],
                     ENV_KEYS["admin_token"], ENV_KEYS["device_token"],
                     ENV_KEYS["device_id"]],
        "values": "set (never printed)",
    })
    if env_mode != 0o600:
        result["ok"] = False
        result.setdefault("errors", []).append("env mode=" + oct(env_mode))

    if not result["ok"]:
        print("prepare_staging_db: FAIL: " + "; ".join(result["errors"]), file=sys.stderr)
        print(json.dumps(result, sort_keys=True))
        return 4

    counts = result["row_counts"]
    print("prepare_staging_db: PASS")
    print("  db               " + result["db"] + " (" + str(result["db_size"]) + " B, mode=" + result["db_mode"] + ")")
    print("  integrity_check  " + result["integrity_check"] + " / quick_check " + result["quick_check"])
    print("  schema_version   " + str(result["schema_version"]))
    print("  journal_mode     " + result["journal_mode"])
    print("  tables           " + str(result["table_count"]) + " (10 app + sqlite_sequence)")
    print("  rows             " + " ".join(k + "=" + str(v) for k, v in sorted(counts.items())))
    print("  admin keys       admin_password=set admin_token=set (values never read/printed)")
    print("  test device      device_id=" + result["device_id"] + " status=" + str(result["device_status"]) +
          " rows=" + str(result["device_rows"]) + " token_hash=sha256(env token) match=" +
          ("yes" if result["device_token_match"] else "no"))
    print("  staging env      " + result["env_out"] + " (mode=" + result["env_mode"] + ", outside git)")
    print("  env keys         " + ", ".join(result["env_keys"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
